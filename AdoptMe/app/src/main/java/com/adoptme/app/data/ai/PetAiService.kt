package com.adoptme.app.data.ai

/**
 * Abstraction over a future server-side pet-care assistant.
 * Implementations must never embed API keys in the Android source.
 */
interface PetAiService {
    suspend fun reply(userMessage: String): String
}

class LocalPetAiService : PetAiService {
    override suspend fun reply(userMessage: String): String {
        val text = userMessage.trim().lowercase()
        if (text.isEmpty()) return "Напишите вопрос об уходе, питании или здоровье питомца."
        if (isEmergency(text)) {
            return "Это может быть экстренная ситуация. Немедленно обратитесь в ближайшую ветеринарную клинику"
        }
        return when {
            matches(text, "корм", "кормить", "питан", "еда", "котён", "котен", "щенк") &&
                matches(text, "чем", "что", "как", "корм", "питан") ->
                feedingAnswer(text)
            matches(text, "дом", "подготов") && matches(text, "собак", "щенк", "питом") ->
                "Перед появлением собаки уберите химию и провода, купите лежанку, миски, поводок и игрушки. " +
                    "Выберите место для сна, договоритесь о правилах и запланируйте спокойные первые дни без гостей."
            matches(text, "привив", "вакцин") ->
                "Базовый курс обычно начинают с 8–9 недель, затем ревакцинация по схеме врача. " +
                    "Точный календарь зависит от возраста и региона — уточните у ветеринара. Я не назначаю препараты."
            matches(text, "адапт", "привык", "стресс") ->
                "Дайте питомцу тихую комнату, не навязывайте объятия и сохраняйте режим кормления. " +
                    "Первые дни лучше короткие прогулки или спокойные игры. Признаки сильного стресса обсудите с ветеринаром."
            matches(text, "гигиен", "мыт", "душ", "когт", "чистк") ->
                "Кошек чаще достаточно расчёсывать и мыть по необходимости. Собак купают по мере загрязнения мягким шампунем. " +
                    "Когти подрезают осторожно, не задевая сосуд. Если не уверены — покажите приём ветеринару или грумеру."
            matches(text, "прогул", "поводок", "выгул") ->
                "Взрослой собаке обычно нужны 2–3 выгула в день. Щенка выводят чаще и короче. " +
                    "До полного курса прививок избегайте людных площадок — это решает ветеринар."
            matches(text, "воспитан", "команд", "туалет", "лоток") ->
                "Коротко, спокойно и последовательно: одна команда — одно действие, поощрение сразу. " +
                    "Наказание криком не помогает. Для лотка держите его чистым и в тихом месте."
            matches(text, "поведен", "агресс", "лает", "царап", "метит") ->
                "Сначала исключите боль и стресс. Затем добавьте режим, прогулки и игру. " +
                    "Если агрессия или метки внезапны — это повод к ветеринару, а не к самостоятельному лечению."
            matches(text, "усынов", "заявк", "приют", "забрать") ->
                "Подготовьте дом, уточните здоровье, питание и характер в приюте. " +
                    "Честно расскажите о жилье и опыте в заявке. Первый месяц — адаптация, не меняйте корм резко."
            matches(text, "помощ", "ран", "травм", "температур") ->
                firstAidAnswer()
            matches(text, "ветеринар", "врач", "клиник") ->
                "Обратитесь в клинику при отказе от еды дольше суток, рвоте, поносе, хромоте, затруднённом дыхании, судорогах или резкой апатии. " +
                    "Я не ставлю диагноз и не назначаю лекарства."
            matches(text, "кошк", "кот") ->
                "Кошке нужны миски, лоток, когтеточка, укрытие и регулярная игра. " +
                    "Кормите по возрасту, не давайте человеческую еду с луком, шоколадом и костями."
            matches(text, "собак", "пёс", "пес", "щен") ->
                "Собаке важны режим прогулок, социализация и понятные правила. " +
                    "Корм подбирайте по размеру и возрасту, воду держите в доступе."
            else ->
                "Я помогу с уходом, питанием, прогулками, адаптацией и подготовкой к усыновлению. " +
                    "Опишите возраст и вид питомца — кошка или собака. При тревожных симптомах сразу идите к ветеринару: я не ставлю диагноз."
        }
    }

    private fun feedingAnswer(text: String): String {
        return if (matches(text, "котён", "котен", "кошк", "кот")) {
            "Котёнка кормят специальным кормом для котят небольшими порциями 3–4 раза в день. " +
                "Молоко с человечьего стола не подходит. Вода должна быть всегда. Переход на новый корм делайте за 5–7 дней."
        } else {
            "Щенка кормят кормом для щенков 3–4 раза в день, взрослую собаку — 1–2 раза. " +
                "Размер порции смотрите на упаковке и по упитанности. Шоколад, виноград, лук и кости опасны."
        }
    }

    private fun firstAidAnswer(): String =
        "Остановите кровотечение чистой тканью, сохраняйте тепло и покой, не давайте человеческие лекарства. " +
            "Это не лечение — как можно скорее покажите питомца ветеринару. " +
            "При судорогах, потере сознания или затруднённом дыхании это может быть экстренная ситуация. Немедленно обратитесь в ближайшую ветеринарную клинику"

    private fun isEmergency(text: String): Boolean {
        val keys = listOf(
            "не дыш", "не дышит", "задыха", "судорог", "конвульс",
            "без сознания", "потерял сознание", "кровотеч", "кровит",
            "отрав", "яд", "температура 40", "не встает", "не встаёт",
            "сильная рвота с кров", "кровав"
        )
        return keys.any { it in text }
    }

    private fun matches(text: String, vararg keys: String): Boolean = keys.any { it in text }
}
